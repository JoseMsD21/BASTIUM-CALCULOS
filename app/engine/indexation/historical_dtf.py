# patron que MemoryRateProvider._buscar_periodo (app/engine/interest/provider.py):
# _DTF_SEMANAL ya se genero en orden ascendente y sin duplicados (verificado
# por el script de carga), asi que basta con tomar sus claves en orden.
_DTF_FECHAS: list[date] = list(_DTF_SEMANAL.keys())

_PRIMERA_FECHA_DISPONIBLE = _DTF_FECHAS[0]


def get_dtf_for_date(fecha: date) -> Decimal:
    """Retorna la tasa DTF (efectiva anual, %) vigente en `fecha`: la de la
    fecha certificada mas reciente que sea <= `fecha` (una certificacion
    semanal rige hasta la siguiente, ver docstring del modulo). Busqueda
    binaria O(log n) sobre _DTF_FECHAS via bisect.bisect_right, igual que
    MemoryRateProvider._buscar_periodo.

    Lanza ValueError si `fecha` es anterior a la primera fecha certificada
    (1984-01-20) -- no hay dato antes de eso y no se inventa uno."""
    if fecha < _PRIMERA_FECHA_DISPONIBLE:
        raise ValueError(
            f"No hay DTF certificada para la fecha {fecha}. "
            f"La serie disponible empieza en {_PRIMERA_FECHA_DISPONIBLE}."
        )

    indice = bisect.bisect_right(_DTF_FECHAS, fecha) - 1
    fecha_certificada = _DTF_FECHAS[indice]
    return _DTF_SEMANAL[fecha_certificada]
